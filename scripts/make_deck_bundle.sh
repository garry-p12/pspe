#!/usr/bin/env bash
# Stage everything an outside slide-building tool needs, in one folder, with
# filenames that carry the slide order.
#
# A tool handed `deck_polder.png` and `16-street-solved.jpg` has no way to know
# which slide either belongs to, and will guess. Numbering the files removes
# the guess.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/docs/deck_bundle"
FIG="$ROOT/docs/figures/deck"
SHOT="$ROOT/docs/images/portal-guide"

rm -rf "$OUT"; mkdir -p "$OUT/images"

cp "$ROOT/docs/DECK_POINTERS.md" "$OUT/OUTLINE.md"
# Source of truth lives OUTSIDE the directory this script wipes, and is copied
# in -- the same pattern as OUTLINE.md, and the reason PROMPT.txt was lost once.
cp "$ROOT/docs/SPEAKER_NOTES.md" "$OUT/SPEAKER_NOTES.md"
cp "$ROOT/docs/DECK_WILDFIRE.md" "$OUT/WILDFIRE_ACT.md"
cp "$ROOT/docs/DECK_REORDER_PROMPT.md" "$OUT/REORDER_PROMPT.md"

# slide number -> source file. Slides with no image are absent by design.
copy() { cp "$2" "$OUT/images/$1"; }

copy "slide-01-title-portal-overview.jpg"        "$SHOT/01-forecast-open.jpg"
copy "slide-03-street-houses-flooded.jpg"        "$SHOT/16-street-solved.jpg"
copy "slide-04-silent-failures.png"              "$FIG/deck_measurement.png"
copy "slide-05-system-architecture.png"          "$FIG/deck_system.png"
copy "slide-06-what-it-offers.png"               "$FIG/deck_offers.png"
copy "slide-07-the-estimator.png"                "$FIG/deck_framework.png"
copy "slide-10-how-the-twin-works.png"           "$FIG/deck_twin_pipeline.png"
copy "slide-11-solved-anywhere.jpg"              "$SHOT/05-forecast-town.jpg"
copy "slide-12-elevation-data-lesson.png"        "$FIG/deck_dem.png"
copy "slide-13-roads-cut.jpg"                    "$SHOT/06-roads-open.jpg"
copy "slide-14-warning-time.png"                 "$FIG/deck_warning.png"
copy "slide-15-the-decision-gym.png"             "$FIG/deck_gym_loop.png"
copy "slide-17-operating-the-structures.png"     "$SHOT/26-operate-result-panel.png"
copy "slide-18-headline-matched-budget.png"      "$FIG/deck_matched_budget.png"
copy "slide-19-safety-violations.png"            "$FIG/deck_margin.png"
copy "slide-20-heuristic-beats-learning.png"     "$FIG/deck_polder.png"
copy "slide-21-why-our-planner-failed.png"       "$FIG/deck_collapse.png"
copy "slide-22-only-three-behaviours.png"        "$FIG/deck_flood_frontier.png"
copy "wildfire-W2-burning-now.jpg"               "$SHOT/32-fire-observe.jpg"
copy "wildfire-W3-forecast-scored.jpg"           "$SHOT/30-fire-forecast.jpg"
copy "wildfire-W5-where-crews-go.jpg"            "$SHOT/31-fire-plan.jpg"
copy "wildfire-W6-vs-operational.png"            "$ROOT/docs/figures/paper/fig4_wildfire.png"
copy "reserve-R1-null-floor.png"                 "$FIG/deck_null_floor.png"
copy "reserve-R2-mixing-rule.png"                "$FIG/deck_mixing_rule.png"

# PROMPT.txt is WRITTEN HERE, not kept in the folder by hand.
#
# It was hand-written into docs/deck_bundle once, and the `rm -rf "$OUT"` at
# the top of this script deleted it on the next run -- silently, because the
# script only regenerates what it knows about. Anything that lives in the
# bundle has to be generated by the thing that rebuilds the bundle.
cat > "$OUT/PROMPT.txt" <<'PROMPTEOF'
Build a presentation from the attached material.

WHAT YOU HAVE
- OUTLINE.md — the full deck: 26 slides in six acts, then reserve slides
  R1–R7, then a caption for every figure.
- SPEAKER_NOTES.md — a spoken script, one entry per slide, with timings.
  Paste each slide's entry into that slide's speaker-notes field.
- images/ — one image per slide. The filename carries the slide number, e.g.
  slide-03-street-houses-flooded.jpg belongs to slide 3. Files beginning
  "reserve-" belong to the reserve slides at the end. Slides with no matching
  file are text-only and need no image.

AUDIENCE
Mixed. Most have no machine-learning background and will not read an equation.
A minority are technical and will ask hard questions. Build for the first
group; the reserve slides exist for the second.

HOW TO USE THE OUTLINE
Each slide has up to four parts, and they go to different places:
- SAY — the headline. Put it at the top of the slide. Keep the wording; it is
  written to be said out loud.
- ON SLIDE — the body bullets. PUT THESE ON THE SLIDE, as bullets, under the
  headline. Two or three per slide. Do not move them to the notes, do not
  summarise them, do not merge them into one line. These are the slide's
  content; a slide with only a headline and a picture is under-filled.
- SHOW — which image goes on that slide.
- IF ASKED — backup detail for questions. NEVER put this on a slide. Speaker
  notes only.

LAYOUT CONSEQUENCE
Most slides therefore carry a headline, two or three bullets, and a figure.
Lay them out so the bullets and the figure share the slide rather than the
figure filling it — figure on one side, bullets on the other, or bullets above
and figure below. Keep the bullets short enough to stay one or two lines each.

DESIGN
- Slides 1, 3, 9, 11 and 13 are the exception: full-bleed screenshot with the
  headline and bullets set beside or over the image, not shrunk into a corner.
- Everywhere else, bullets and figure share the slide as described above.
- Never more than three bullets on a slide. The outline does not give more
  than three; do not invent a fourth.
- Do not add clip art, stock photography, icons or decorative gradients. Every
  visual is already supplied and is either a measured figure or a screenshot of
  the real system.
- Readable at the back of a room: minimum 20pt body, 28pt+ headlines, high
  contrast. The figures are vector-sharp; do not upscale the raster versions.
- One consistent, restrained template throughout. Dark text on light ground.

CONTENT RULES — these matter more than the design
- Do NOT invent, round, or "clean up" any number. Every figure in images/ was
  generated from measured data. If a number is not in OUTLINE.md or visible in
  a figure, it does not go on a slide.
- Do NOT add a slide claiming a result that is not in the outline. In
  particular do not write a summary slide that says the method wins
  everywhere — the outline deliberately includes results where it loses
  (slides 20, 21, 24) and those slides stay.
- Keep the honesty slides. Act VI is not optional padding.
- Keep the figure captions (end of OUTLINE.md) in the speaker notes of their
  slide. Do not print them on the slide.

OUTPUT
- Slides 1–26 in order, then reserve slides R1–R7 clearly marked as backup,
  after the closing slide.
- Speaker notes on every slide, taken from SPEAKER_NOTES.md. Keep the wording;
  it is written to be spoken. Where a slide also has IF ASKED in OUTLINE.md,
  append that to the same notes field under a line reading "IF ASKED".
- Editable format (PowerPoint or Google Slides), 16:9.
PROMPTEOF

cat > "$OUT/README.txt" <<'TXT'
WHAT IS IN HERE

  OUTLINE.md   the deck: 26 slides in six acts, then reserve slides R1-R7,
               then a caption for every figure.
  SPEAKER_NOTES.md
               what to actually say, slide by slide, with timings. Read this
               one standing up.
  WILDFIRE_ACT.md
               the second application, eight slides, same format. Slots in
               after the flood act.
  REORDER_PROMPT.md
               paste this into the slide tool together with everything else.
               It says what order to build and what is wrong with the
               current one.
  images/      one file per slide that has an image. The filename carries the
               slide number from OUTLINE.md. Slides not listed here are text
               only and need no image.

HOW TO READ THE OUTLINE

  Each slide has SAY (the line to deliver), SHOW (which image), and sometimes
  IF ASKED (backup detail for questions, NOT for the slide body).

  Put SAY on the slide or in the speaker notes. Never put IF ASKED on a slide.

PNG is supplied. Vector versions (svg, pdf) of every figure are in
docs/figures/deck/ if the tool accepts them -- they will stay sharp at any
projector size.
TXT

# Fail loudly if the bundle is missing a part. The failure this prevents was
# silent: a deleted PROMPT.txt still produced a bundle that looked fine.
missing=0
for f in OUTLINE.md SPEAKER_NOTES.md WILDFIRE_ACT.md REORDER_PROMPT.md \
         PROMPT.txt README.txt; do
  [ -s "$OUT/$f" ] || { echo "MISSING $f" >&2; missing=1; }
done
[ "$(ls "$OUT/images" | wc -l | tr -d ' ')" -eq 24 ] || {
  echo "expected 24 images, found $(ls "$OUT/images" | wc -l | tr -d ' ')" >&2
  missing=1
}
[ "$missing" -eq 0 ] || exit 1

echo "staged $(ls "$OUT/images" | wc -l | tr -d ' ') images + OUTLINE.md + SPEAKER_NOTES.md + PROMPT.txt + README.txt"
du -sh "$OUT"
